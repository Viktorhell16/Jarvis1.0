    private val kaomojiSymbols = arrayOf("(★)", "[⚡]", "{✦}", "<◈>", "(^_^)", "[>_]", "✦", "❖", "⌘", "◈")

    fun verbCount(): Int = verbs.size
    fun topicCount(): Int = topics.size

    fun promptAt(index: Int, seed: Long): String {
        val safeIdx = ((index % TOTAL_COMBINATIONS) + TOTAL_COMBINATIONS) % TOTAL_COMBINATIONS
        if (safeIdx < featuredStarters.size) {
            return featuredStarters[safeIdx]
        }
        // Permute linearly via coprime multiplier (3733) over 10,000 combinations
        val offset = ((seed % TOTAL_COMBINATIONS) + TOTAL_COMBINATIONS).toInt()
        val permuted = ((safeIdx - featuredStarters.size) * 3733 + offset) % TOTAL_COMBINATIONS
        val verbIdx = permuted / topics.size
        val topicIdx = permuted % topics.size
        return "${verbs[verbIdx]} ${topics[topicIdx]}"
    }

    fun displayPromptAt(index: Int, seed: Long, emojiStyle: EmojiStyle): String {
        val base = promptAt(index, seed)
        val safeIdx = ((index % TOTAL_COMBINATIONS) + TOTAL_COMBINATIONS) % TOTAL_COMBINATIONS
        return when (emojiStyle) {
            EmojiStyle.SYSTEM -> "${systemEmojis[safeIdx % systemEmojis.size]} $base"
            EmojiStyle.IOS_FLUENT -> "${iosFluentEmojis[safeIdx % iosFluentEmojis.size]} $base"
            EmojiStyle.MINIMAL_KAOMOJI -> "${kaomojiSymbols[safeIdx % kaomojiSymbols.size]} $base"
            EmojiStyle.NONE -> base
        }
    }

    fun nextShuffleSeed(current: Long): Long = Random(current xor System.nanoTime()).nextLong()
